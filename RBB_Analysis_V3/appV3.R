      need(nrow(data_hourly) > 0,
           "No hourly summary data (File 7) available for circadian analysis.")
    )
    # Ensure BinStartTime is POSIXct
    if (nrow(data_hourly) > 0 && !inherits(data_hourly$BinStartTime, "POSIXct")) {
      data_hourly[, BinStartTime := as.POSIXct(
        BinStartTime, origin="1970-01-01", tz="UTC"
      )]
    }
    validate(
      need(inherits(data_hourly$BinStartTime, "POSIXct"),
           "BinStartTime in File 7 could not be converted to POSIXct.")
    )
    
    # Reshape data
    plot_cols <- intersect(COUNT_COL_NAMES, names(data_hourly))
    validate(
      need(length(plot_cols) > 0,
           "No 'Count_*' columns found in File 7 data.")
    )
    data_long <- tryCatch(
      melt(data_hourly, id.vars = "BinStartTime", measure.vars = plot_cols,
           variable.name = "Label", value.name = "Count", na.rm = TRUE),
      error = function(e) {
        warning("Error melting File 7 data for circadian: ", e$message)
        NULL
      }
    )
    validate(
      need(!is.null(data_long) && nrow(data_long) > 0,
           "Failed to reshape File 7 data or no count data for circadian.")
    )
    data_long[, Label := gsub("Count_", "", Label)]
    
    # Add HourOfDay column (UTC)
    data_long[, HourOfDay := lubridate::hour(BinStartTime)]
    
    # Aggregate total counts by HourOfDay and Label
    circadian_data <- data_long[,
                                .(TotalCount = sum(Count, na.rm = TRUE)),
                                by = .(HourOfDay, Label)
    ]
    validate(
      need(nrow(circadian_data) > 0, "No data after circadian aggregation.")
    )
    
    # Generate plot
    ggplot(circadian_data, aes(x = HourOfDay, y = TotalCount)) +
      geom_col(fill = "seagreen") +
      facet_wrap(~ Label, scales = "free_y", ncol = 4) +
      labs(
        title = "Circadian Pattern (Total Counts per Hour of Day)",
        subtitle = "Aggregated across selected date range (UTC)",
        x = "Hour of Day (UTC)",
        y = "Total Count"
      ) +
      theme_bw(base_size = 10) +
      theme(
        axis.text.x = element_text(size = 8),
        strip.text = element_text(size = 8)
      ) +
      # Set X-axis breaks to show hours
      scale_x_continuous(breaks = seq(0, 23, by = 2))
    
  }, height = 600)
  
  
  output$plot_wheel_daily <- renderPlot({
    data_wheel_raw <- loaded_wheel(); validate(need(nrow(data_wheel_raw) > 0, "...")); validate(need(all(c("Timestamp", "Wheel_Movement") %in% names(data_wheel_raw)), "..."), need(inherits(data_wheel_raw$Timestamp, "POSIXct"), "..."), need(is.numeric(data_wheel_raw$Wheel_Movement), "..."))
    data_wheel_daily <- data_wheel_raw[, .(Daily_Wheel_Movement = sum(Wheel_Movement, na.rm = TRUE)), by = .(Date = as.Date(Timestamp))]; validate(need(nrow(data_wheel_daily) > 0, "..."))
    date_range_days <- as.numeric(diff(range(data_wheel_daily$Date, na.rm = TRUE))); date_break_setting <- if (is.na(date_range_days) || date_range_days <= 7) {"1 day"} else if (date_range_days <= 60) {"1 week"} else if (date_range_days <= 365) {"1 month"} else {"3 months"}; date_label_format <- if (date_range_days <= 90) {"%m-%d"} else {"%Y-%m"}
    ggplot(data_wheel_daily, aes(x = Date, y = Daily_Wheel_Movement)) + geom_col(fill = "darkorange") + labs(title = "Total Daily Wheel Movement", x = "Date", y = "Total Movement (Sum of diffs)") + theme_bw(base_size = 10) + theme( axis.text.x = element_text(angle = 45, vjust = 1, hjust = 1, size = 8) ) + scale_x_date( date_breaks = date_break_setting, date_labels = date_label_format ) + scale_y_continuous(labels = scales::label_number(accuracy = 0.1))
  }, height = 600)
  
  
  # == Table Tabs ==
  
  output$tbl_hourly <- DT::renderDataTable({
    data <- loaded_file7(); validate(need(nrow(data) > 0, "...")); if (!"POSIXct" %in% class(data$BinStartTime)) { data[, BinStartTime := as.POSIXct( BinStartTime, origin = "1970-01-01", tz = "UTC" )] }; validate( need(inherits(data$BinStartTime,"POSIXct"),"...") )
    data_display <- copy(data); data_display[, BinStartTime_Formatted := format( BinStartTime, format = '%Y-%m-%d %H:%M:%S', tz = 'UTC' )]
    data_for_dt <- data_display[, !"BinStartTime"]; setnames(data_for_dt, "BinStartTime_Formatted", "BinStartTime"); if ("BinStartTime" %in% names(data_for_dt)) { setcolorder(data_for_dt, neworder = "BinStartTime") }
    datatable( data_for_dt, options = list( pageLength = 15, scrollX = TRUE, searchDelay = 500 ), rownames = FALSE, filter = 'top' )
  }, server = TRUE)
  
  output$tbl_daily <- DT::renderDataTable({
    data <- loaded_file8(); validate(need(nrow(data) > 0, "...")); if (nrow(data) > 0 && !inherits(data$BinStartTime, "Date")) { data[, BinStartTime := as.Date(BinStartTime)] }; validate(need(inherits(data$BinStartTime,"Date"), "..."))
    data_display <- copy(data); if ("BinStartTime" %in% names(data_display)) { setcolorder(data_display, neworder = "BinStartTime") }
    datatable( data_display, options = list( pageLength = 15, scrollX = TRUE, searchDelay = 500 ), rownames = FALSE, filter = 'top' )
  })
  
  output$tbl_file5 <- DT::renderDataTable({
    data <- loaded_file5(); validate(need(nrow(data) > 0, "...")); validate(need(all(c("StartTime", "Label", "Duration") %in% names(data)),"...")); if (!"POSIXct" %in% class(data$StartTime)) { data[, StartTime := as.POSIXct( StartTime, origin = "1970-01-01", tz = "UTC" )] }; validate(need(inherits(data$StartTime,"POSIXct"), "..."))
    data_display <- copy(data)[, Duration := round(Duration, 3)]; data_display[, StartTime_Formatted := format( StartTime, format = '%Y-%m-%d %H:%M:%S', tz = 'UTC' )]
    datatable( data_display[, .(StartTime = StartTime_Formatted, Label, Duration)], options = list( pageLength = 15, scrollX = TRUE, searchDelay = 500 ), rownames = FALSE, filter = 'top' )
  }, server = TRUE)
  
  
  # --- Download Handlers ---
  
  output$download_hourly <- downloadHandler(
    filename = function() { paste0("hourly_binned_data_", input$experiment, "_", input$cohort, "_", input$rat, "_", Sys.Date(), ".csv") }, content = function(file) { data_to_save <- loaded_file7(); data.table::fwrite(data_to_save, file) }
  )
  
  output$download_daily <- downloadHandler(
    filename = function() { paste0("daily_binned_data_", input$experiment, "_", input$cohort, "_", input$rat, "_", Sys.Date(), ".csv") }, content = function(file) { data_to_save <- loaded_file8(); data.table::fwrite(data_to_save, file) }
  )
  
  output$download_file5 <- downloadHandler(
    filename = function() { paste0("labeled_events_file5_", input$experiment, "_", input$cohort, "_", input$rat, "_", Sys.Date(), ".csv") }, content = function(file) { data_to_save <- loaded_file5(); data.table::fwrite(data_to_save, file) }
  )
  
