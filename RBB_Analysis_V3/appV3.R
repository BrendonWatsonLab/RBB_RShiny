# Description:
#   Optimized R Shiny app for visualizing pre-processed RBB data.
#   Uses a pre-generated manifest file ('processed_manifest.rds') for fast
#   file discovery. Uses caching (shiny::bindCache) and efficient data
#   loading (data.table). Reads processed files and displays:
#   - Daily Beambreak Count Plots (from File 8) - Daily X-axis labels
#   - Hourly Beambreak Count Plots (from File 7) - Daily X-axis labels
#   - Circadian Analysis Plot (Aggregated hourly counts from File 7)
#   - Hourly Bin Data Table (from File 7)
#   - Daily Bin Data Table (from File 8)
#   - Labeled Events Table (from File 5)
#   - Daily Wheel Movement Plot (from WheelMovement files)
#   Formats datetime columns for tables within R server logic using base::format.
#
# Data Source: Reads 'processed_manifest.rds' and associated data files from
#              the processed_data_dir. Manifest file must be generated by
#              the 'RBB_LocalAnalysis.R' script and include entries for
#              File 5, File 7, File 8, and WheelMovement.
# Dependencies: shiny (>= 1.6.0), DT, data.table, dplyr, tidyr, scales,
#               lubridate, stringr, ggplot2, shinycssloaders, bit64
# ============================================================================

